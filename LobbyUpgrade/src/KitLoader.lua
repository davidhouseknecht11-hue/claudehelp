-- KitLoader  (ModuleScript, child of the LobbyUpgrade script)
--
-- Finds the Blender kit ("LobbyKit", imported with File > Import 3D), fixes its scale,
-- and hands out coloured, ready-to-place copies of each prop.
--
-- Mesh names from Blender look like   Prop__piece__colorKey__anim
--   colorKey -> PALETTE below (colour, material, transparency)
--   anim     -> "spin40", "bob0.5", "spin40_bob0.5" ... played on each player's screen by KitAnimator

local ServerStorage = game:GetService("ServerStorage")
local ReplicatedStorage = game:GetService("ReplicatedStorage")
local CollectionService = game:GetService("CollectionService")
local TweenService = game:GetService("TweenService")

local Kit = {}
Kit.Loaded = false

-- generated by blender_lobby_kit.py (keep in sync with PAL in that file)
local PALETTE = {
--@PALETTE@
}

local props = {} -- [propName] = { pieces = { {part, piece, color, anim} }, anchor = part?, front = part? }

local function parse(name)
	name = string.gsub(name, "_Node$", "") -- Studio's importer adds "_Node" to the wrapper models
	local bits = string.split(name, "__")
	if #bits < 3 then
		return nil
	end
	local color = string.match(bits[3], "^%a+") or bits[3] -- ignore any suffix the importer added
	return bits[1], bits[2], color, bits[4]
end

-- The kit can sit in ServerStorage, ReplicatedStorage or Workspace, under any name.
local function findKitParts()
	for _, where in ipairs({ ServerStorage, ReplicatedStorage, workspace }) do
		for _, d in ipairs(where:GetDescendants()) do
			if d:IsA("BasePart") and string.sub(d.Name, 1, 16) == "ScaleRef__cube__" then
				-- climb to the outermost Model that holds the kit
				-- (Workspace itself counts as a Model, so stop before it)
				local top = d.Parent
				while top.Parent and top.Parent ~= where and top.Parent:IsA("Model") do
					top = top.Parent
				end
				local parts = {}
				for _, p in ipairs(top:GetDescendants()) do
					if p:IsA("BasePart") and parse(p.Name) then
						table.insert(parts, p)
					end
				end
				if top == where then
					-- loose meshes dropped straight into a service: gather them into one model
					top = Instance.new("Model")
					top.Name = "LobbyKit"
					top.Parent = ServerStorage
					for _, p in ipairs(parts) do
						p.Parent = top
					end
				end
				return top, parts, d
			end
		end
	end
	return nil
end

function Kit.load()
	local top, parts, ref = findKitParts()
	if not top then
		return false
	end

	-- freeze everything first (imported meshes are often unanchored)
	for _, p in ipairs(parts) do
		p.Anchored = true
	end

	-- The Blender kit is built 1 unit = 1 stud. Whatever unit the importer used, the 10-stud
	-- reference cube tells us how to get back to that.
	local s = 10 / math.max(ref.Size.X, ref.Size.Y, ref.Size.Z)
	if math.abs(s - 1) > 0.02 then
		local about = ref.Position
		for _, p in ipairs(parts) do
			local cf = p.CFrame
			p.Size = p.Size * s
			p.CFrame = CFrame.new(about + (cf.Position - about) * s) * cf.Rotation
		end
		print(("[LobbyUpgrade] Kit rescaled x%.3f"):format(s))
	end

	-- keep the kit out of the world while the game runs
	if top:IsDescendantOf(workspace) then
		top.Parent = ServerStorage
	end

	for _, p in ipairs(parts) do
		local prop, piece, colorKey, anim = parse(p.Name)
		local def = props[prop]
		if not def then
			def = { pieces = {} }
			props[prop] = def
		end
		if piece == "anchor" then
			def.anchor = p
		elseif piece == "front" then
			def.front = p
		else
			table.insert(def.pieces, { part = p, piece = piece, color = colorKey, anim = anim })
		end
	end

	Kit.Loaded = true
	return true
end

function Kit.has(name)
	return props[name] ~= nil and #props[name].pieces > 0
end

local function style(part, key, opts)
	local e = PALETTE[key] or PALETTE.white
	local color = e[1]
	if key == "tint" and opts.tint then
		color = opts.tint
	end
	part.Color = color
	part.Material = Enum.Material[e[2]]
	part.Transparency = e[3]
	part:SetAttribute("KitT", e[3])
	part.Anchored = true
	part.CanCollide = false
	part.CanTouch = false
	part.CanQuery = false
	part.Massless = true
	part.CastShadow = opts.shadows ~= false and e[2] ~= "Neon"
	for _, c in ipairs(part:GetChildren()) do
		if c:IsA("SurfaceAppearance") or c:IsA("Decal") or c:IsA("Texture") then
			c:Destroy()
		end
	end
	if part:IsA("MeshPart") then
		pcall(function()
			part.TextureID = ""
		end)
	end
end

-- where the prop's own origin is inside the imported kit
local function propPivot(def)
	local pos
	if def.anchor then
		pos = def.anchor.Position
	else
		-- no anchor mesh survived the import: use the bottom centre of the prop
		local lo, hi
		for _, piece in ipairs(def.pieces) do
			local p = piece.part
			local a, b = p.Position - p.Size / 2, p.Position + p.Size / 2
			lo = lo and Vector3.new(math.min(lo.X, a.X), math.min(lo.Y, a.Y), math.min(lo.Z, a.Z)) or a
			hi = hi and Vector3.new(math.max(hi.X, b.X), math.max(hi.Y, b.Y), math.max(hi.Z, b.Z)) or b
		end
		pos = Vector3.new((lo.X + hi.X) / 2, lo.Y, (lo.Z + hi.Z) / 2)
	end
	if def.anchor and def.front then
		local dir = def.front.Position - def.anchor.Position
		dir = Vector3.new(dir.X, 0, dir.Z)
		if dir.Magnitude > 0.01 then
			return CFrame.lookAt(pos, pos + dir) -- prop "front" becomes the pivot's look direction
		end
	end
	return CFrame.new(pos)
end

-- Kit.spawn("Pillar", cframe, { scale = 1, parent = folder, tint = Color3, shadows = false, name = "..",
--                               motion = { kind = "bob" | "orbit" | "follow", ... } })
-- The prop's front (if it has one) points along cframe.LookVector.
function Kit.spawn(name, cf, opts)
	local def = props[name]
	if not def or #def.pieces == 0 then
		return nil
	end
	opts = opts or {}
	local scale = opts.scale or 1
	local motion = opts.motion
	local pivot = propPivot(def)

	local model = Instance.new("Model")
	model.Name = opts.name or name

	local root = Instance.new("Part")
	root.Name = "KitRoot"
	root.Size = Vector3.new(1, 1, 1)
	root.Transparency = 1
	root.Anchored = true
	root.CanCollide = false
	root.CanTouch = false
	root.CanQuery = false
	root.CFrame = cf
	root.Parent = model
	model.PrimaryPart = root

	local animated = motion ~= nil
	for _, piece in ipairs(def.pieces) do
		local part = piece.part:Clone()
		local rel = pivot:ToObjectSpace(part.CFrame)
		rel = CFrame.new(rel.Position * scale) * rel.Rotation
		part.Name = piece.piece
		part.Size = part.Size * scale
		part.CFrame = cf * rel
		style(part, piece.color, opts)
		if piece.anim or motion then
			part:SetAttribute("KitRel", rel)
			if piece.anim then
				part:SetAttribute("KitAnim", piece.anim)
				animated = true
			end
		end
		part.Parent = model
	end

	if motion then
		model:SetAttribute("KitMotion", motion.kind)
		model:SetAttribute("KitBase", cf)
		model:SetAttribute("KitPhase", motion.phase or 0)
		model:SetAttribute("KitSpeed", motion.speed or 1)
		model:SetAttribute("KitAmp", motion.amp or 0)
		if motion.center then
			model:SetAttribute("KitCenter", motion.center)
		end
		if motion.radius then
			model:SetAttribute("KitRadius", motion.radius)
		end
		if motion.target then
			local ov = Instance.new("ObjectValue")
			ov.Name = "KitTarget"
			ov.Value = motion.target
			ov.Parent = model
		end
	end
	if opts.noCull then
		model:SetAttribute("KitNoCull", true)
	end
	if animated then
		CollectionService:AddTag(model, "KitModel")
	end
	model.Parent = opts.parent or workspace
	return model
end

-- Fade a spawned prop in (visible = true) or out (visible = false).
function Kit.fade(model, visible, seconds)
	for _, d in ipairs(model:GetDescendants()) do
		if d:IsA("BasePart") and d.Name ~= "KitRoot" then
			local goal = visible and (d:GetAttribute("KitT") or 0) or 1
			TweenService:Create(d, TweenInfo.new(seconds), { Transparency = goal }):Play()
		end
	end
end

-- Copies the named props into `folder` (in ReplicatedStorage) so client scripts (shop icons,
-- disaster effects) can clone them. They are untagged, so KitAnimator leaves the templates alone.
function Kit.publish(names, folder)
	for _, name in ipairs(names) do
		local model = Kit.spawn(name, CFrame.new(), { parent = folder, shadows = false })
		if model then
			CollectionService:RemoveTag(model, "KitModel")
		end
	end
end

function Kit.setTransparency(model, value)
	for _, d in ipairs(model:GetDescendants()) do
		if d:IsA("BasePart") and d.Name ~= "KitRoot" then
			d.Transparency = value
		end
	end
end

return Kit
